-- Secure anonymous FIT quote access.
-- Anonymous users never receive direct access to FIT base tables: every read and
-- action resolves the private token server-side and returns an explicit safe shape.

alter table public.fit_quotes
  add column if not exists public_link_expires_at timestamptz,
  add column if not exists public_link_revoked_at timestamptz,
  add column if not exists public_client_visible boolean not null default false,
  add column if not exists public_last_viewed_at timestamptz,
  add column if not exists public_client_status text,
  add column if not exists public_deposit_mad numeric;

-- Existing enabled links remain usable, while becoming explicitly client-visible.
update public.fit_quotes
set public_client_visible = true
where share_enabled = true
  and share_token is not null
  and public_client_visible = false;

create unique index if not exists fit_quotes_share_token_uidx
  on public.fit_quotes (share_token)
  where share_token is not null;

create index if not exists fit_quotes_public_link_active_idx
  on public.fit_quotes (share_enabled, public_link_expires_at)
  where deleted_at is null and share_token is not null;

create table if not exists public.fit_quote_public_audit_events (
  id bigint generated by default as identity primary key,
  quote_id uuid not null references public.fit_quotes(id) on delete cascade,
  event text not null check (event in ('opened', 'accepted', 'revision_requested', 'declined')),
  occurred_at timestamptz not null default now(),
  actor_type text not null default 'anonymous_client' check (actor_type = 'anonymous_client'),
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists fit_quote_public_audit_quote_time_idx
  on public.fit_quote_public_audit_events (quote_id, occurred_at desc);

alter table public.fit_quote_public_audit_events enable row level security;

revoke all on public.fit_quote_public_audit_events from anon, authenticated;

-- Remove every historical anonymous path to FIT records. Authenticated staff access
-- remains controlled by the existing RLS policies.
