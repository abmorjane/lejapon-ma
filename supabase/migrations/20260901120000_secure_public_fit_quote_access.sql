-- Authenticated link management centralizes cryptographically secure token creation.
create or replace function public.regenerate_public_fit_quote_token(p_quote_id uuid, p_expires_at timestamptz default null)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_token text;
begin
  if auth.uid() is null or not public.can_access_fit_quote(p_quote_id, auth.uid()) then
    raise exception 'not authorized';
  end if;
  v_token := encode(extensions.gen_random_bytes(32), 'hex');
  update public.fit_quotes
  set share_token = v_token,
      share_enabled = true,
      public_client_visible = true,
      public_link_expires_at = p_expires_at,
      public_link_revoked_at = null,
      public_client_status = coalesce(public_client_status, 'quoted')
  where id = p_quote_id;
  return jsonb_build_object('token', v_token, 'expires_at', p_expires_at, 'enabled', true);
end;
$$;

create or replace function public.set_public_fit_quote_link(
  p_quote_id uuid,
  p_enabled boolean,
  p_expires_at timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_token text;
begin
  if auth.uid() is null or not public.can_access_fit_quote(p_quote_id, auth.uid()) then
    raise exception 'not authorized';
  end if;
  select share_token into v_token from public.fit_quotes where id = p_quote_id;
  if p_enabled and v_token is null then raise exception 'generate a token first'; end if;
  update public.fit_quotes
  set share_enabled = p_enabled,
      public_client_visible = case when p_enabled then true else public_client_visible end,
      public_link_expires_at = p_expires_at,
      public_link_revoked_at = case when p_enabled then null else statement_timestamp() end
  where id = p_quote_id;
  return jsonb_build_object('enabled', p_enabled, 'expires_at', p_expires_at);
end;
$$;

